export function searchDestinations(query) {
  if (!query || typeof query !== "string") return [];
  const cleanQuery = query.trim().toLowerCase();
  if (cleanQuery === "") return [];

  return DESTINATIONS_META.filter((dest) => {
    // Check ID
    if (dest.id.toLowerCase().includes(cleanQuery)) return true;
    // Check English Name
    if (dest.enName.toLowerCase().includes(cleanQuery)) return true;
    // Check Bengali Name
    if (dest.bnName.toLowerCase().includes(cleanQuery)) return true;
    // Check English Tag
    if (dest.enTag.toLowerCase().includes(cleanQuery)) return true;
    // Check Bengali Tag
    if (dest.bnTag.toLowerCase().includes(cleanQuery)) return true;
    // Check all keywords
    return dest.keywords.some((kw) => {
      const cleanKw = kw.toLowerCase();
      return cleanKw.includes(cleanQuery) || cleanQuery.includes(cleanKw);
    });
  });
}
